int main(int argc, char **argv) {
  ssize_t i = 0;
  const char *env_val = NULL;

  /*
   * BIG FAT WARNING: Do not attempt to build kloak with NDEBUG defined. Many
   * of the assertions in this code are essential for security, and building
   * kloak with NDEBUG defined will turn all of them off. Systems running a
   * build of kloak with NDEBUG defined should be treated as compromised if
   * they process any form of untrusted data.
   *
   * To lower the risk of this situation occurring, the following check will
   * render kloak non-functional if NDEBUG is defined. Think very carefully
   * about what you are doing if you are considering patching this check out.
   */
#ifdef NDEBUG
  fprintf(stderr,
    "FATAL ERROR: Built with NDEBUG set. kloak does not support this, please rebuild with NDEBUG unset.\n");
  exit(1);
#endif

  if (getuid() != 0) {
    fprintf(stderr, "FATAL ERROR: Must be run as root!\n");
    exit(1);
  }

  /* Make sure that locales don't try to ruin our day */
  if (setenv("LC_ALL", "C", 1) == -1) {
    fprintf(stderr, "FATAL ERROR: Could not set LC_ALL=C!\n");
    exit(1);
  }

  parse_cli_args(argc, argv);
  env_val = getenv("KLOAK_EXIT_ON_WL_CONNECT_FAILURE");
  if (env_val != NULL && strcmp(env_val, "1") == 0) {
    exit_on_wl_connect_failure = true;
  }

  if (sleep_ms(startup_delay) != 0) {
    fprintf(stderr,
      "FATAL ERROR: Could not sleep for requested start duration!\n");
    exit(1);
  }

  applayer_random_init();
  applayer_wayland_init();
  applayer_libinput_init();
  applayer_inotify_init();
  applayer_poll_init();

  if (did_wayland_init) {
    while (true) {
      while (wl_display_prepare_read(state.display) != 0) {
        wl_display_dispatch_pending(state.display);
      }
      wl_display_flush_safe(state.display);

      while (true) {
        enum libinput_event_type next_ev_type = libinput_next_event_type(li);
        struct libinput_event *li_event = NULL;

        if (next_ev_type == LIBINPUT_EVENT_NONE)
          break;

        li_event = libinput_get_event(li);
        register_esc_combo_event(li_event);
        queue_libinput_event_and_relocate_virtual_cursor(li_event);
        /*
         * We do NOT free the libinput event here.
         * queue_libinput_event_and_relocate_virtual_cursor will destroy the
         * event if appropriate, or queue it for future release and
         * destruction otherwise.
         */
      }

      release_scheduled_input_events();

      for (i = 0; i < MAX_SCREEN_COUNT; i++) {
        if (!state.layers[i]) {
          continue;
        }
        if (state.layers[i]->frame_pending) {
          assert(should_draw_cursor);
          draw_frame(state.layers[i]);
        }
      }
      wl_display_flush_safe(state.display);

      if (poll(ev_fds, POLL_FD_COUNT, calc_poll_timeout()) == -1) {
        fprintf(stderr, "FATAL ERROR: 'poll' errored out: %s\n",
          strerror(errno));
        exit(1);
      }

      if (ev_fds[2].revents & POLLIN) {
        if (wl_display_read_events(state.display) == -1) {
          fprintf(stderr,
            "FATAL ERROR: Could not read events from Wayland server: %s\n",
            strerror(errno));
          exit(1);
        }
        wl_display_dispatch_pending(state.display);
      } else {
        wl_display_cancel_read(state.display);
      }
      /*
       * Note that it's also possible for ev_fds[2].revents to have POLLOUT
       * set. We can ignore that here because we will attempt to write to the
       * display server FD on the next iteration through the loop anyway.
       */
      ev_fds[2].revents = 0;

      if (ev_fds[0].revents & POLLIN) {
        libinput_dispatch(li);
      }
      ev_fds[0].revents = 0;

      if (ev_fds[1].revents & POLLIN) {
        handle_inotify_events();
      }
      ev_fds[1].revents = 0;
    }

    /* Control never reaches this point. */
  } else {
    while(true) {
      while (true) {
        enum libinput_event_type next_ev_type = libinput_next_event_type(li);
        struct libinput_event *li_event = NULL;

        if (next_ev_type == LIBINPUT_EVENT_NONE)
          break;

        li_event = libinput_get_event(li);
        register_esc_combo_event(li_event);
        /*
         * We have to free the libinput event here ourselves since we don't
         * call queue_libinput_event_and_relocate_virtual_cursor (which would
         * either destroy it or queue it for later release and destruction).
         */
        libinput_event_destroy(li_event);
      }

      if (poll(ev_fds, POLL_FD_COUNT - 1, -1) == -1) {
        fprintf(stderr, "FATAL ERROR: 'poll' errored out: %s\n",
          strerror(errno));
        exit(1);
      }

      if (ev_fds[0].revents & POLLIN) {
        libinput_dispatch(li);
      }
      ev_fds[0].revents = 0;

      if (ev_fds[1].revents & POLLIN) {
        handle_inotify_events();
      }
      ev_fds[1].revents = 0;
    }
  }
  return 0;
}

