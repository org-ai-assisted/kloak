static void layer_surface_configure(void *data,
  struct zwlr_layer_surface_v1 *layer_surface, uint32_t serial, uint32_t width,
  uint32_t height) {

  struct disp_state *param_state = data;
  struct drawable_layer *layer = NULL;
  ssize_t i = 0;
  int shm_fd = 0;
  struct wl_region *zeroed_region = NULL;
  struct kloak_layer_dims dims = { 0 };

  assert(should_draw_cursor);

  for (i = 0; i < MAX_SCREEN_COUNT; i++) {
    if (param_state->layers[i]) {
      if (param_state->layers[i]->layer_surface == layer_surface) {
        layer = param_state->layers[i];
        break;
      }
    }
  }
  assert(layer != NULL);
  /* Validate width/height + derive stride / size in int64_t.
   * The previous inline arithmetic computed 'stride * height' in
   * int32_t and only then asserted the bounds; under -ftrapv
   * the multiplication would trap before the assertion could
   * fire. compute_layer_dims_pure() does every step in int64_t
   * and rejects on overflow. Production callers see real
   * compositor dimensions and never hit the rejection path; a
   * hostile compositor would. */
  dims = compute_layer_dims_pure(width, height);
  if (!dims.valid) {
    fprintf(stderr,
      "FATAL ERROR: Compositor reported layer dimensions kloak cannot represent (%ux%u).\n",
      width, height);
    exit(1);
  }
  layer->width  = dims.width;
  layer->height = dims.height;
  layer->stride = dims.stride;
  layer->size   = dims.size;
  shm_fd = create_shm_file(layer->size * MAX_UNRELEASED_FRAMES);
  if (shm_fd == -1) {
    fprintf(stderr,
      "FATAL ERROR: Cannot allocate shared memory block for frame: %s\n",
      strerror(errno));
    exit(1);
  }
  layer->pixbuf = mmap(NULL, (size_t)(layer->size * MAX_UNRELEASED_FRAMES), PROT_READ | PROT_WRITE,
    MAP_SHARED, shm_fd, 0);
  if (layer->pixbuf == MAP_FAILED) {
    safe_close(shm_fd);
    fprintf(stderr,
      "FATAL ERROR: Failed to map shared memory block for frame: %s\n",
      strerror(errno));
    exit(1);
  }
  layer->shm_pool = wl_shm_create_pool(param_state->shm, shm_fd,
    layer->size * MAX_UNRELEASED_FRAMES);

  zeroed_region = wl_compositor_create_region(param_state->compositor);
  wl_region_add(zeroed_region, 0, 0, 0, 0);
  wl_surface_set_input_region(layer->surface, zeroed_region);

  zwlr_layer_surface_v1_ack_configure(layer_surface, serial);
  layer->layer_surface_configured = true;
  wl_region_destroy(zeroed_region);
  draw_frame(layer);
}

