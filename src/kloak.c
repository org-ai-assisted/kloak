static void read_random(char *buf, ssize_t len) {
  assert(len >= 0);
  assert(randfd > 0);
  assert(buf != NULL);

  if (read(randfd, buf, (size_t)(len)) < len) {
    fprintf(stderr,
      "FATAL ERROR: Could not read %ld byte(s) from /dev/urandom!\n", len);
    exit(1);
  }
}

static void randname(char *buf, ssize_t len) {
  char randchar = 0;

  assert(len >= 0);
  assert(buf != NULL);

  for (ssize_t i = 0; i < len; i++) {
    do {
      read_random(&randchar, 1);
      if (randchar == CHAR_MIN) {
        randchar = 0;
      } else {
        randchar = (char)(abs(randchar));
      }
    } while (randchar >= (CHAR_MAX - (CHAR_MAX % ALPHABET_LEN)));

    randchar %= (ALPHABET_LEN * 2);
    if (randchar < ALPHABET_LEN) {
      randchar += ASCII_UPPERCASE_START;
    } else {
      randchar += ASCII_LOWERCASE_START;
    }
    buf[i] = randchar;
  }
}

static int create_shm_file(ssize_t size) {
  int32_t retries = 100;
  int fd = -1;
  /* 18 = length of string '/kloak-XXXXXXXXXX' + NULL terminator */
  char name[18];
  int snprintf_len = 0;
  int32_t ret = 0;

  assert(should_draw_cursor);
  assert(size >= 0);
  /*
   * In a perfect world, we'd do the sizeof check here at compile time, but
   * unfortunately that isn't possible.
   */
  if (sizeof(off_t) == 4) {
    assert(size <= INT32_MAX);
  } else if (sizeof(off_t) == 8) {
    assert(size <= INT64_MAX);
  } else {
    fprintf(stderr,
      "FATAL ERROR: off_t is not 32-bit or 64-bit, cannot continue\n");
    exit(1);
  }

  do {
    snprintf_len = snprintf(name, sizeof(name), "%s", "/kloak-XXXXXXXXXX");
    assert(snprintf_len > 0 && (size_t)(snprintf_len) == sizeof(name) - 1);
    /* 10 = length of 'XXXXXXXXXX', 11 = length + NULL terminator */
    randname(name + sizeof(name) - 11, 10);
    --retries;
    fd = shm_open(name, O_RDWR | O_CREAT | O_EXCL | O_CLOEXEC, 0600);
    if (fd >= 0) {
      shm_unlink(name);
      break;
    }
  } while (retries > 0 && errno == EEXIST);

  if (fd == -1) {
    fprintf(stderr,
      "FATAL ERROR: Could not create shared memory fd: %s\n",
      strerror(errno));
    exit(1);
  }

  do {
    ret = ftruncate(fd, (off_t)(size));
  } while (ret < 0 && errno == EINTR);
  if (ret < 0) {
    close(fd);
    fprintf(stderr,
      "FATAL ERROR: Could not allocate shared memory block: %s\n",
      strerror(errno));
    exit(1);
  }

  return fd;
}

static int64_t current_time_ms(void) {
  struct timespec spec = { 0 };
  int64_t result = 0;

  clock_gettime(CLOCK_MONOTONIC, &spec);
  assert(spec.tv_sec < INT64_MAX);
  result = ((int64_t)spec.tv_sec * 1000) + (spec.tv_nsec / 1000000);
  assert(result >= 0);
  if (start_time == 0) {
    start_time = result;
    return 0;
  }
  return result - start_time;
}

static int64_t random_between(int64_t lower, int64_t upper) {
  int64_t maxval = 0;
  union rand_int64 randval;

  assert(lower >= 0);
  assert(upper >= 0);

  /* default to max if the interval is not valid */
  if (lower >= upper) {
    return upper;
  }

  maxval = upper - lower + 1;
  assert(maxval > 0);
  do {
    read_random(randval.raw, sizeof(int64_t));
    if (randval.val == INT64_MIN) {
      randval.val = 0;
    } else {
      randval.val = llabs(randval.val);
    }
  } while (randval.val >= (INT64_MAX - (INT64_MAX % maxval)));

  randval.val %= maxval;
  return lower + randval.val;
}


/* recalc_global_space()'s body moved to src/kloak_recalc.inc.h
 * as recalc_global_space_pure(); this wrapper does the same
 * thing on the disp_state global. The gap-detection panic stays
 * here (the pure helper returns KLOAK_RECALC_GAP instead so it
 * is callable from the fuzz harness). */
static void recalc_global_space(struct disp_state *param_state) {
  struct kloak_recalc_result r = recalc_global_space_pure(
    param_state->output_geometries, MAX_SCREEN_COUNT);
  switch (r.status) {
    case KLOAK_RECALC_INCOMPLETE:
      /* Silently fail if we haven't gotten a valid state yet */
      return;
    case KLOAK_RECALC_GAP:
      fprintf(stderr,
        "FATAL ERROR: Multiple screens are attached and gaps are present between them. kloak cannot operate in this configuration.\n");
      exit(1);
    case KLOAK_RECALC_OK:
      param_state->global_space_width = r.global_space_width;
      param_state->global_space_height = r.global_space_height;
      param_state->pointer_space_x = r.pointer_space_x;
      param_state->pointer_space_y = r.pointer_space_y;
      return;
    default:
      /* Unreachable; the pure helper only returns the three
       * statuses above. The default case exists to satisfy
       * -Wswitch-default. */
      return;
  }
}

