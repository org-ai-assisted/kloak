static void draw_frame(struct drawable_layer *layer) {
  int32_t chosen_frame_idx = -1;
  int32_t frame_idx = 0;
  struct wl_buffer *buffer = NULL;
  struct screen_local_coord scr_coord = { 0 };
  bool cursor_is_on_layer = false;
  ssize_t layer_idx = 0;

  assert(should_draw_cursor);

  if (!layer->layer_surface_configured)
    return;

  for (frame_idx = 0; frame_idx < MAX_UNRELEASED_FRAMES; frame_idx++) {
    if (!layer->frame_in_use[frame_idx]) {
      chosen_frame_idx = frame_idx;
      break;
    }
  }
  if (chosen_frame_idx == -1) {
    return;
  }

  layer->frame_pending = false;

  assert(layer->size >= 0);
  assert(chosen_frame_idx >= 0);
  assert((layer->size * chosen_frame_idx)
    < (layer->size * MAX_UNRELEASED_FRAMES));
  buffer = wl_shm_pool_create_buffer(layer->shm_pool,
    layer->size * chosen_frame_idx, layer->width, layer->height,
    layer->stride, WL_SHM_FORMAT_ARGB8888);

  assert(cursor_x < INT32_MAX && cursor_x >= 0);
  assert(cursor_y < INT32_MAX && cursor_y >= 0);
  scr_coord = abs_coord_to_screen_local_coord((int32_t)(cursor_x),
    (int32_t)(cursor_y));

  cursor_is_on_layer = false;
  if (scr_coord.valid) {
    for (layer_idx = 0; layer_idx < MAX_SCREEN_COUNT; layer_idx++) {
      if ((state.layers[layer_idx] == layer)
        && (layer_idx == scr_coord.output_idx)) {
        cursor_is_on_layer = true;
      }
    }
  }

  if (layer->last_drawn_cursor_x >= 0 && layer->last_drawn_cursor_y >= 0) {
    /* Damage the previous cursor location */
    damage_surface_enh(layer->surface,
      layer->last_drawn_cursor_x - CURSOR_RADIUS,
      layer->last_drawn_cursor_y - CURSOR_RADIUS,
      layer->last_drawn_cursor_x + CURSOR_RADIUS + 1,
      layer->last_drawn_cursor_y + CURSOR_RADIUS + 1);
  }
  if (cursor_is_on_layer) {
    /* Draw crosshairs at the pointer location */
    draw_block(layer->pixbuf, (layer->size * chosen_frame_idx) / 4,
      scr_coord.x, scr_coord.y, layer->width, layer->height, CURSOR_RADIUS,
      true, cursor_color);
    damage_surface_enh(layer->surface, scr_coord.x - CURSOR_RADIUS,
      scr_coord.y - CURSOR_RADIUS, scr_coord.x + CURSOR_RADIUS + 1,
      scr_coord.y + CURSOR_RADIUS + 1);
  }

  wl_buffer_add_listener(buffer, &buffer_listener, NULL);
  layer->buffer_list[chosen_frame_idx] = buffer;
  wl_surface_attach(layer->surface, buffer, 0, 0);
  wl_surface_commit(layer->surface);
  if (cursor_is_on_layer) {
    layer->last_drawn_cursor_x = scr_coord.x;
    layer->last_drawn_cursor_y = scr_coord.y;
  } else {
    layer->last_drawn_cursor_x = -1;
    layer->last_drawn_cursor_y = -1;
  }
  layer->cursor_x_pos_list[chosen_frame_idx] = layer->last_drawn_cursor_x;
  layer->cursor_y_pos_list[chosen_frame_idx] = layer->last_drawn_cursor_y;
  layer->frame_in_use[chosen_frame_idx] = true;
}

static struct drawable_layer *allocate_drawable_layer(struct disp_state *param_state,
  struct wl_output *output) {
  struct drawable_layer *layer = safe_calloc(1, sizeof(struct drawable_layer));
  ssize_t i = 0;

  layer->last_drawn_cursor_x = -1;
  layer->last_drawn_cursor_y = -1;
  for (i = 0; i < MAX_UNRELEASED_FRAMES; i++) {
    layer->cursor_x_pos_list[i] = -1;
    layer->cursor_y_pos_list[i] = -1;
  }
  layer->output = output;

  if (should_draw_cursor) {
    layer->frame_pending = true;
    layer->surface = wl_compositor_create_surface(param_state->compositor);
    if (!layer->surface) {
      fprintf(stderr, "FATAL ERROR: Could not create Wayland surface!\n");
      exit(1);
    }
    layer->layer_surface = zwlr_layer_shell_v1_get_layer_surface(
      param_state->layer_shell, layer->surface, layer->output,
      ZWLR_LAYER_SHELL_V1_LAYER_OVERLAY, "com.kicksecure.kloak");
    zwlr_layer_surface_v1_add_listener(layer->layer_surface,
      &layer_surface_listener, param_state);

    zwlr_layer_surface_v1_set_anchor(
      layer->layer_surface,
      ZWLR_LAYER_SURFACE_V1_ANCHOR_TOP |
      ZWLR_LAYER_SURFACE_V1_ANCHOR_BOTTOM |
      ZWLR_LAYER_SURFACE_V1_ANCHOR_LEFT |
      ZWLR_LAYER_SURFACE_V1_ANCHOR_RIGHT
    );
    zwlr_layer_surface_v1_set_exclusive_zone(layer->layer_surface, -1);
    wl_surface_commit(layer->surface);
  }

  return layer;
}

static void damage_surface_enh(struct wl_surface *surface, int32_t x,
  int32_t y, int32_t width, int32_t height) {
  assert(should_draw_cursor);
  assert(width >= 0);
  assert(height >= 0);
  if (x < 0) x = 0;
  if (y < 0) y = 0;
  wl_surface_damage_buffer(surface, x, y, width, height);
}

static struct input_packet * update_virtual_cursor(void) {
  struct screen_local_coord prev_scr_coord = { 0 };
  int32_t i = 0;
  struct coord start = { 0 };
  struct coord end = { 0 };
  struct kloak_walk_cursor_result walk_result = { 0 };
  struct screen_local_coord scr_coord = { 0 };
  struct input_packet *old_ev_packet = NULL;
  struct input_packet *ev_packet = NULL;

  assert(prev_cursor_x < INT32_MAX && prev_cursor_x >= 0);
  assert(prev_cursor_y < INT32_MAX && prev_cursor_y >= 0);

  prev_scr_coord = abs_coord_to_screen_local_coord((int32_t)(prev_cursor_x),
    (int32_t)(prev_cursor_y));

  if (!prev_scr_coord.valid || !state.layers[prev_scr_coord.output_idx]) {
    /* We've somehow gotten into a spot where the previous coordinate data
     * either is invalid or points at an area where there is no screen. Reset
     * everything in the hopes of recovering sanity. */
    printf("Resetting!\n");
    for (i = 0; i < MAX_SCREEN_COUNT; i++) {
      if (state.layers[i]) {
        struct coord sane_location = screen_local_coord_to_abs_coord(0, 0, i);

        prev_cursor_x = sane_location.x;
        prev_cursor_y = sane_location.y;
        cursor_x = sane_location.x;
        cursor_y = sane_location.y;
        assert(prev_cursor_x < INT32_MAX && prev_cursor_x >= 0);
        assert(prev_cursor_y < INT32_MAX && prev_cursor_y >= 0);
        prev_scr_coord = abs_coord_to_screen_local_coord(
          (int32_t)(prev_cursor_x), (int32_t)(prev_cursor_y));
        break;
      }
    }
  }

  /*
   * Ensure the cursor doesn't move off-screen, and recalculate its end
   * position if it would end up off-screen.
   *
   * This is a bit tricky to do since we can't just look at the intended final
   * location of the mouse and move it there if that location is valid, since
   * that would allow jumping over "voids" in the compositor global space
   * (places where global space has a pixel but no screen covers that pixel).
   * Instead, we use the following algorithm:
   *
   * - Take the previous cursor position and treat it as a "start location".
   *   Treat the current cursor position as an "end location".
   * - Start walking in a straight line from the start location to the end
   *   location, one pixel at a time.
   * - Once we hit the end location, move the real mouse cursor there.
   * - Each time we walk forward a pixel, calculate the screen-local
   *   coordinates of that pixel, and ensure it actually is on a screen.
   * - If a pixel is NOT on any screen, determine which direction we can move
   *   to get back onto a screen. Move one pixel in that direction, then
   *   change the start location to this new position and adjust the end
   *   location so that we can walk to it moving in a straight line without
   *   moving any further in the dimension we just moved to get back to a
   *   screen. I.e., if we moved horizontally to the left one pixel to get
   *   back on a screen, move the end location so that we can walk to it in a
   *   vertical line. This allows us to "glide" along the wall.
   *
   * There may be a more efficient algorithm for this. Contributions welcome.
   */

  assert(cursor_x < INT32_MAX && cursor_x >= 0);
  assert(cursor_y < INT32_MAX && cursor_y >= 0);
  start.x = (int32_t)(prev_cursor_x);
  start.y = (int32_t)(prev_cursor_y);
  end.x = (int32_t)(cursor_x);
  end.y = (int32_t)(cursor_y);
  /* The glide-along-wall loop body lives in kloak_walk_cursor.
   * inc.h; the pure helper takes the geometries by parameter
   * and returns the final cursor position so the fuzz harness
   * can exercise it without the disp_state global. Production
   * passes INT32_MAX for max_iterations because the walk is
   * bounded by manhattan distance between start and end
   * (already int32). */
  walk_result = walk_cursor_pure(start, end, state.output_geometries,
    MAX_SCREEN_COUNT, INT32_MAX);
  if ((int32_t)(cursor_x) != walk_result.final_pos.x) {
    cursor_x = walk_result.final_pos.x;
  }
  if ((int32_t)(cursor_y) != walk_result.final_pos.y) {
    cursor_y = walk_result.final_pos.y;
  }
  assert(cursor_x < INT32_MAX && cursor_x >= 0);
  assert(cursor_y < INT32_MAX && cursor_y >= 0);
  scr_coord = abs_coord_to_screen_local_coord((int32_t)(cursor_x),
    (int32_t)(cursor_y));

  if (should_draw_cursor) {
    state.layers[prev_scr_coord.output_idx]->frame_pending = true;
    state.layers[scr_coord.output_idx]->frame_pending = true;
  }

  /* = rather than == is intentional here */
  if ((old_ev_packet = TAILQ_LAST(&evq_head, tailhead_evq))
    && (old_ev_packet->packet_type == KLOAK_PACKET_TYPE_MOUSEMOVE)) {
    old_ev_packet->data.mousemove.cursor_x = (int32_t)(cursor_x);
    old_ev_packet->data.mousemove.cursor_y = (int32_t)(cursor_y);
    return NULL;
  } else {
    ev_packet = safe_calloc(1, sizeof(struct input_packet));
    ev_packet->packet_type = KLOAK_PACKET_TYPE_MOUSEMOVE;
    ev_packet->data.mousemove.cursor_x = (int32_t)(cursor_x);
    ev_packet->data.mousemove.cursor_y = (int32_t)(cursor_y);
    return ev_packet;
  }
}

static struct input_packet *update_mouse_scroll(void) {
  int32_t vert_scroll_ticks = get_ticks_from_scroll_accum(&vert_scroll_accum);
  int32_t horiz_scroll_ticks = get_ticks_from_scroll_accum(
    &horiz_scroll_accum);
  struct input_packet *old_ev_packet = NULL;
  struct input_packet *ev_packet = NULL;

  if ((vert_scroll_ticks != 0) || (horiz_scroll_ticks != 0)) {
    if ((old_ev_packet = TAILQ_LAST(&evq_head, tailhead_evq))
      && (old_ev_packet->packet_type == KLOAK_PACKET_TYPE_MOUSESCROLL)) {
      old_ev_packet->data.mousescroll.vert_scroll_ticks += vert_scroll_ticks;
      old_ev_packet->data.mousescroll.horiz_scroll_ticks
        += horiz_scroll_ticks;
      return NULL;
    } else {
      ev_packet = safe_calloc(1, sizeof(struct input_packet));
      ev_packet->packet_type = KLOAK_PACKET_TYPE_MOUSESCROLL;
      ev_packet->data.mousescroll.vert_scroll_ticks = vert_scroll_ticks;
      ev_packet->data.mousescroll.horiz_scroll_ticks = horiz_scroll_ticks;
      return ev_packet;
    }
  }

  return NULL;
}

static void handle_libinput_event(struct libinput_event *li_event,
  uint32_t ts_milliseconds) {
  bool mouse_event_handled = false;
  enum libinput_event_type ev_type = libinput_event_get_type(li_event);
  struct libinput_device *ev_device = libinput_event_get_device(li_event);
  struct li_device_info *ev_device_info = libinput_device_get_user_data(
    ev_device
  );
  assert(ev_device_info != NULL);

  if (ev_type == LIBINPUT_EVENT_DEVICE_ADDED) {
    struct libinput_device *new_dev = libinput_event_get_device(li_event);
    int can_tap = libinput_device_config_tap_get_finger_count(new_dev);

    if (can_tap) {
      libinput_device_config_tap_set_enabled(new_dev,
        LIBINPUT_CONFIG_TAP_ENABLED);
    }

  } else if (ev_type == LIBINPUT_EVENT_POINTER_BUTTON) {
    struct libinput_event_pointer *pointer_event
      = libinput_event_get_pointer_event(li_event);
    uint32_t button_code = libinput_event_pointer_get_button(pointer_event);
    enum libinput_button_state button_state
      = libinput_event_pointer_get_button_state(pointer_event);

    mouse_event_handled = true;

    if (button_state == LIBINPUT_BUTTON_STATE_PRESSED) {
      /* Both libinput and zwlr_virtual_pointer_v1 use evdev event codes to
       * identify the button pressed, so we can just pass the data from
       * libinput straight through */
      zwlr_virtual_pointer_v1_button(
        state.virt_pointer, ts_milliseconds, button_code,
        WL_POINTER_BUTTON_STATE_PRESSED);
    } else {
      zwlr_virtual_pointer_v1_button(
        state.virt_pointer, ts_milliseconds, button_code,
        WL_POINTER_BUTTON_STATE_RELEASED);
    }

  } else if (ev_type == LIBINPUT_EVENT_KEYBOARD_KEY) {
    if (state.virt_kb_keymap_set) {
      struct libinput_event_keyboard *kb_event
        = libinput_event_get_keyboard_event(li_event);
      uint32_t key = libinput_event_keyboard_get_key(kb_event);
      enum libinput_key_state key_state
        = libinput_event_keyboard_get_key_state(kb_event);
      enum libinput_led led_state = 0;
      xkb_mod_mask_t depressed_mods;
      xkb_mod_mask_t latched_mods;
      xkb_mod_mask_t locked_mods;
      xkb_layout_index_t effective_group;

      if (key_state == LIBINPUT_KEY_STATE_PRESSED) {
        /* XKB keycodes == evdev keycodes + 8. Why this design decision was
         * made, I have no idea. */
        xkb_state_update_key(state.xkb_state, key + 8, XKB_KEY_DOWN);
      } else {
        xkb_state_update_key(state.xkb_state, key + 8, XKB_KEY_UP);
      }
      depressed_mods = xkb_state_serialize_mods(
        state.xkb_state, XKB_STATE_MODS_DEPRESSED);
      latched_mods = xkb_state_serialize_mods(
        state.xkb_state, XKB_STATE_MODS_LATCHED);
      locked_mods = xkb_state_serialize_mods(
        state.xkb_state, XKB_STATE_MODS_LOCKED);
      effective_group = xkb_state_serialize_layout(
        state.xkb_state, XKB_STATE_LAYOUT_EFFECTIVE);
      zwp_virtual_keyboard_v1_modifiers(state.virt_kb, depressed_mods,
        latched_mods, locked_mods, effective_group);
      zwp_virtual_keyboard_v1_key(state.virt_kb, ts_milliseconds, key,
        key_state);

      /* Generally, X11 and Wayland turn an LED on after a key press, and
       * off after a key release. The exact reason for this is unclear, but
       * we mimic that behavior here to make sure we don't trip any weird
       * edge cases that depend on this. */
      if (key == KEY_NUMLOCK) {
        if (key_state == LIBINPUT_KEY_STATE_PRESSED
          && !ev_device_info->num_lock_held) {
          ev_device_info->num_lock_held = true;
          ev_device_info->num_lock_state += 1;
        } else if (key_state == LIBINPUT_KEY_STATE_RELEASED) {
          ev_device_info->num_lock_held = false;
          ev_device_info->num_lock_state += 1;
        }
        if (ev_device_info->num_lock_state == 4) {
          ev_device_info->num_lock_state = 0;
        }
      } else if (key == KEY_CAPSLOCK) {
        if (key_state == LIBINPUT_KEY_STATE_PRESSED
          && !ev_device_info->caps_lock_held) {
          ev_device_info->caps_lock_held = true;
          ev_device_info->caps_lock_state += 1;
        } else if (key_state == LIBINPUT_KEY_STATE_RELEASED) {
          ev_device_info->caps_lock_held = false;
          ev_device_info->caps_lock_state += 1;
        }
        if (ev_device_info->caps_lock_state == 4) {
          ev_device_info->caps_lock_state = 0;
        }
      }
      if (ev_device_info->num_lock_state != 0) {
        led_state |= LIBINPUT_LED_NUM_LOCK;
      }
      if (ev_device_info->caps_lock_state != 0) {
        led_state |= LIBINPUT_LED_CAPS_LOCK;
      }
      if (led_state != ev_device_info->last_led_state) {
        ev_device_info->last_led_state = led_state;
        libinput_device_led_update(ev_device, led_state);
      }
    }
  }

  if (mouse_event_handled) {
    zwlr_virtual_pointer_v1_frame(state.virt_pointer);
  }

  li_device_info_unref(ev_device_info);
  libinput_event_destroy(li_event);
}

static void register_esc_combo_event(struct libinput_event *li_event) {
  struct libinput_event_keyboard *kb_event = NULL;
  uint32_t key = 0;
  enum libinput_key_state key_state = LIBINPUT_KEY_STATE_PRESSED;
  enum libinput_event_type li_event_type = libinput_event_get_type(li_event);

  if (li_event_type != LIBINPUT_EVENT_KEYBOARD_KEY) {
    return;
  }

  kb_event = libinput_event_get_keyboard_event(li_event);
  key = libinput_event_keyboard_get_key(kb_event);
  key_state = libinput_event_keyboard_get_key_state(kb_event);

  if (esc_combo_update(key, key_state == LIBINPUT_KEY_STATE_PRESSED,
        esc_key_list, esc_key_sublist_len, esc_key_list_len,
        active_esc_key_list)) {
    exit(0);
  }
}

static void queue_libinput_event_and_relocate_virtual_cursor(
  struct libinput_event *li_event) {
  struct input_packet *ev_packet = NULL;
  struct libinput_event_pointer *pointer_event = NULL;
  struct libinput_device *ev_device = NULL;
  struct li_device_info *ev_device_info = NULL;
  enum libinput_event_type li_event_type = libinput_event_get_type(li_event);
  double abs_x = 0.0;
  double abs_y = 0.0;
  double rel_x = 0.0;
  double rel_y = 0.0;
  double vert_scroll_val = 0.0;
  double horiz_scroll_val = 0.0;
  int64_t current_time = 0;
  int64_t lower_bound = 0;
  int64_t random_delay = 0;

  if (li_event_type == LIBINPUT_EVENT_POINTER_MOTION_ABSOLUTE) {
    pointer_event = libinput_event_get_pointer_event(li_event);
    assert(state.global_space_width >= 0);
    assert(state.global_space_height >= 0);
    abs_x = libinput_event_pointer_get_absolute_x_transformed(
      pointer_event, (uint32_t)(state.global_space_width));
    abs_y = libinput_event_pointer_get_absolute_y_transformed(
      pointer_event, (uint32_t)(state.global_space_height));
    prev_cursor_x = cursor_x;
    prev_cursor_y = cursor_y;
    cursor_x = abs_x;
    cursor_y = abs_y;
    ev_packet = update_virtual_cursor();
    libinput_event_destroy(li_event);
    if (!ev_packet) {
      return;
    }

  } else if (li_event_type == LIBINPUT_EVENT_POINTER_MOTION) {
    pointer_event = libinput_event_get_pointer_event(li_event);
    rel_x = libinput_event_pointer_get_dx(pointer_event);
    rel_y = libinput_event_pointer_get_dy(pointer_event);
    prev_cursor_x = cursor_x;
    prev_cursor_y = cursor_y;
    cursor_x += rel_x;
    cursor_y += rel_y;
    if (cursor_x < state.pointer_space_x) cursor_x = state.pointer_space_x;
    if (cursor_y < state.pointer_space_y) cursor_y = state.pointer_space_y;
    if (cursor_x > state.global_space_width - 1)
      cursor_x = state.global_space_width - 1;
    if (cursor_y > state.global_space_height - 1)
      cursor_y = state.global_space_height - 1;
    ev_packet = update_virtual_cursor();
    libinput_event_destroy(li_event);
    if (!ev_packet) {
      return;
    }

  /*
   * Scroll event handling is somewhat tricky...
   *
   * We want to mask the kind of scrolling device the user is using. To do
   * this, we add together all mouse scroll events in an accumulator, then
   * translate what's in the accumulator into scroll events as appropriate.
   * The intended user experience is:
   *
   * - "Clicky" mouse wheel rotationr: the page should scroll some quantity
   *   with every "click". Emphasis on "click" here. We do NOT want to output
   *   scroll events with values matching the user's actual scrolling too
   *   precisely, so we do NOT want to say "if the user's mouse wheel rotated
   *   7.33116 degrees, scroll 7.33116 units" or similar.
   * - Everything else (smooth mouse wheel rotation, two-finger scrolling,
   *   continuous scrolling, future high-resolution scrolling methods humanity
   *   dreams up in their nightmares): the page should scroll a "mouse click's
   *   worth" of distance after enough scroll distance has accumulated.
   *
   * libinput has at least four different ways of representing scroll
   * movement. Unfortunately, none of them are suitable in all situations.
   *
   * - libinput_event_pointer_get_scroll_value() returns a double indicating
   *   some distance of movement. For scroll wheels, this corresponds to the
   *   angle (in degrees) the wheel rotated. For touch and continuous inputs,
   *   this corresponds to some quantity of "relative motion" (an abstract
   *   term the libinput API documentation does not elaborate on, but one
   *   assumes it correlates reasonably with mouse wheel rotation angles).
   *   This is great until you realize that mouse wheels sometimes rotate
   *   different quantities with each "tick" (and mice that don't have mouse
   *   wheel ticks look the same as mice with "clicky" mouse wheels when using
   *   libinput). This means that if we just use this function for everything,
   *   some users will see no scrolling after rotating the scroll wheel one
   *   click, then after a few "working" clicks they'll get a click that
   *   scrolls twice as far as expected. Other users will always have to
   *   scroll multiple clicks to get one "click's worth" of scrolling, and
   *   other users will (almost) always get multiple "click's worth"s of
   *   scrolling.
   * - libinput_event_pointer_get_scroll_value_v120() fixes the above mess by
   *   representing scroll distance in terms of mouse wheel clicks rather than
   *   raw angles. The function returns a double equal to (number of mouse
   *   ticks * 120), with support for "fractional ticks" in the form of values
   *   not evenly divisible by 120. By using this function, we can translate
   *   scroll ticks directly into quantities of scroll movement on screen, no
   *   matter how many degrees the wheel turns per tick. Unfortunately, this
   *   function *only* supports scroll wheel events, it doesn't work with any
   *   other kind of scrolling.
   * - libinput_event_pointer_get_axis_value() and
   *   libinput_event_pointer_get_axis_value_discrete() are similar to the
   *   above, but the values they provide are different (their output is in
   *   "relative scroll units" and "discrete steps", respectively), the latter
   *   doesn't work with high-resolution scroll devices, and both are
   *   deprecated.
   *
   * To achieve the desired user experience given the above API, the scroll
   * accumulator's value represents 1/120ths of a scroll tick (the same value
   * used by the v120 function above). For scroll wheels, we can thus use the
   * output of the v120 function directly. For everything else, we assume that
   * a scroll wheel tick always corresponds to 15 degrees of mouse wheel
   * rotation from the standpoint of libinput_event_pointer_get_scroll_value()
   * (this is a blatantly false assumption but it's close enough for our
   * purposes, since the "default" degrees of rotation per wheel click is 15
   * in libinput), and thus we can translate the output of
   * libinput_event_pointer_get_scroll_value() into a value suitable for use
   * in our accumulator by multiplying it by 8 (because 120 / 15 = 8).
   *
   * This is further complicated by the fact that there are both vertical and
   * horizontal scroll events, so we actually have two scroll accumulators,
   * one for each dimension.
   */
  } else if (li_event_type == LIBINPUT_EVENT_POINTER_SCROLL_WHEEL) {
    pointer_event = libinput_event_get_pointer_event(li_event);
    if (libinput_event_pointer_has_axis(pointer_event,
      LIBINPUT_POINTER_AXIS_SCROLL_VERTICAL)) {
      vert_scroll_val = libinput_event_pointer_get_scroll_value_v120(
        pointer_event, LIBINPUT_POINTER_AXIS_SCROLL_VERTICAL);
    }
    if (libinput_event_pointer_has_axis(pointer_event,
      LIBINPUT_POINTER_AXIS_SCROLL_HORIZONTAL)) {
      horiz_scroll_val = libinput_event_pointer_get_scroll_value_v120(
        pointer_event, LIBINPUT_POINTER_AXIS_SCROLL_HORIZONTAL);
    }
    vert_scroll_accum += vert_scroll_val;
    horiz_scroll_accum += horiz_scroll_val;
    ev_packet = update_mouse_scroll();
    libinput_event_destroy(li_event);
    if (!ev_packet) {
      return;
    }

  } else if ((li_event_type == LIBINPUT_EVENT_POINTER_SCROLL_FINGER)
    || (li_event_type == LIBINPUT_EVENT_POINTER_SCROLL_CONTINUOUS)) {
    pointer_event = libinput_event_get_pointer_event(li_event);
    if (libinput_event_pointer_has_axis(pointer_event,
      LIBINPUT_POINTER_AXIS_SCROLL_VERTICAL)) {
      /*
       * Note that IEEE-754 floating point math does not have undefined
       * behavior on overflow/underflow. If we're using some weird compiler
       * and CPU combination that doesn't use IEEE-754, this might be
       * undefined behavior, but this is pretty rare, see:
       * https://lwn.net/Articles/886516/
       */
      vert_scroll_val = libinput_event_pointer_get_scroll_value(
        pointer_event, LIBINPUT_POINTER_AXIS_SCROLL_VERTICAL)
        * SCROLL_ANGLE_TO_UNITS_FACTOR_D;
    }
    if (libinput_event_pointer_has_axis(pointer_event,
      LIBINPUT_POINTER_AXIS_SCROLL_HORIZONTAL)) {
      horiz_scroll_val = libinput_event_pointer_get_scroll_value(
        pointer_event, LIBINPUT_POINTER_AXIS_SCROLL_HORIZONTAL)
        * SCROLL_ANGLE_TO_UNITS_FACTOR_D;
    }
    vert_scroll_accum += vert_scroll_val;
    horiz_scroll_accum += horiz_scroll_val;
    ev_packet = update_mouse_scroll();
    libinput_event_destroy(li_event);
    if (!ev_packet) {
      return;
    }

  } else if ((li_event_type == LIBINPUT_EVENT_DEVICE_ADDED)
    || (li_event_type == LIBINPUT_EVENT_POINTER_BUTTON)
    || (li_event_type == LIBINPUT_EVENT_KEYBOARD_KEY)) {
    ev_packet = safe_calloc(1, sizeof(struct input_packet));
    if (ev_packet == NULL) {
      fprintf(stderr,
        "FATAL ERROR: Could not allocate memory for libinput event packet!\n");
      exit(1);
    }
    ev_packet->packet_type = KLOAK_PACKET_TYPE_LIBINPUT;
    ev_packet->data.libinput.li_event = li_event;
    ev_device = libinput_event_get_device(li_event);
    ev_device_info = libinput_device_get_user_data(ev_device);
    assert(ev_device_info != NULL);
    li_device_info_ref(ev_device_info);
  } else {
    /*
     * Other libinput events (like gestures) can't actually be passed through
     * via the virtual-keyboard-unstable-v1 or wlr-virtual-pointer-unstable-v1
     * protocols; we'd have to create our own handlers for those. We don't
     * have any such handlers, so simply ignore those events.
     */
    libinput_event_destroy(li_event);
    return;
  }

  current_time = current_time_ms();
  lower_bound = min(max(prev_release_time - current_time, 0), max_delay);
  random_delay = random_between(lower_bound, max_delay);
  ev_packet->sched_time = current_time + random_delay;
  TAILQ_INSERT_TAIL(&evq_head, ev_packet, entries);
  prev_release_time = ev_packet->sched_time;
}

static void release_scheduled_input_events(void) {
  int64_t current_time = current_time_ms();
  struct input_packet *packet = NULL;

  while ((packet = TAILQ_FIRST(&evq_head))
    && (current_time >= packet->sched_time)) {
    /*
     * These conditionals are intentionally ordered so that more common events
     * are processed earlier, don't re-order them unless you have to.
     */
    if (packet->packet_type == KLOAK_PACKET_TYPE_MOUSEMOVE) {
      assert(packet->sched_time >= 0);
      if (packet->sched_time > UINT32_MAX) {
        fprintf(stderr,
          "packet->sched_time overflowed maximum value. This is not an error, but kloak must be restarted. Exiting.");
        exit(0);
      }
      assert(state.pointer_space_x >= 0);
      assert(state.pointer_space_y >= 0);
      assert(packet->data.mousemove.cursor_x >= state.pointer_space_x);
      assert(packet->data.mousemove.cursor_y >= state.pointer_space_y);
      assert(state.global_space_width >= state.pointer_space_x);
      assert(state.global_space_height >= state.pointer_space_y);
      zwlr_virtual_pointer_v1_motion_absolute(
        state.virt_pointer, (uint32_t)(packet->sched_time),
        (uint32_t)(packet->data.mousemove.cursor_x - state.pointer_space_x),
        (uint32_t)(packet->data.mousemove.cursor_y - state.pointer_space_y),
        (uint32_t)(state.global_space_width - state.pointer_space_x),
        (uint32_t)(state.global_space_height - state.pointer_space_y));
      zwlr_virtual_pointer_v1_frame(state.virt_pointer);

    } else if (packet->packet_type == KLOAK_PACKET_TYPE_LIBINPUT) {
      assert(packet->sched_time >= 0);
      if (packet->sched_time > UINT32_MAX) {
        fprintf(stderr,
          "packet->sched_time overflowed maximum value. This is not an error, but kloak must be restarted. Exiting.");
        exit(0);
      }
      handle_libinput_event(packet->data.libinput.li_event,
        (uint32_t)(packet->sched_time));

    } else { /* packet->packet_type == KLOAK_PACKET_TYPE_MOUSESCROLL */
      bool send_axis_source_and_frame = false;
      assert(packet->packet_type == KLOAK_PACKET_TYPE_MOUSESCROLL);
      assert(packet->sched_time >= 0);
      if (packet->sched_time > UINT32_MAX) {
        fprintf(stderr,
          "packet->sched_time overflowed maximum value. This is not an error, but kloak must be restarted. Exiting.");
        exit(0);
      }
      if (packet->data.mousescroll.vert_scroll_ticks != 0) {
        zwlr_virtual_pointer_v1_axis(state.virt_pointer,
          (uint32_t)(packet->sched_time), WL_POINTER_AXIS_VERTICAL_SCROLL,
          wl_fixed_from_int(packet->data.mousescroll.vert_scroll_ticks
            * SCROLL_ANGLE_PER_TICK));
        zwlr_virtual_pointer_v1_axis_discrete(state.virt_pointer,
          (uint32_t)(packet->sched_time), WL_POINTER_AXIS_VERTICAL_SCROLL,
          wl_fixed_from_int(SCROLL_ANGLE_PER_TICK),
          packet->data.mousescroll.vert_scroll_ticks);
        send_axis_source_and_frame = true;
      }
      if (packet->data.mousescroll.horiz_scroll_ticks != 0) {
        zwlr_virtual_pointer_v1_axis(state.virt_pointer,
          (uint32_t)(packet->sched_time), WL_POINTER_AXIS_HORIZONTAL_SCROLL,
          wl_fixed_from_int(packet->data.mousescroll.horiz_scroll_ticks
            * SCROLL_ANGLE_PER_TICK));
        zwlr_virtual_pointer_v1_axis_discrete(state.virt_pointer,
          (uint32_t)(packet->sched_time), WL_POINTER_AXIS_HORIZONTAL_SCROLL,
          wl_fixed_from_int(SCROLL_ANGLE_PER_TICK),
            packet->data.mousescroll.horiz_scroll_ticks);
        send_axis_source_and_frame = true;
      }
      if (send_axis_source_and_frame) {
        zwlr_virtual_pointer_v1_axis_source(state.virt_pointer,
          WL_POINTER_AXIS_SOURCE_WHEEL);
        zwlr_virtual_pointer_v1_frame(state.virt_pointer);
      }
    }
    TAILQ_REMOVE(&evq_head, packet, entries);
    free(packet);
  }
}

static void dispatch_inotify_event(const struct inotify_event *ie) {
  /* Per inotify(7) the 'name' field is optional: when present it
   * is always NUL-terminated (and NUL-padded out to 'len'), so
   * strncmp would honour the terminator. When ie->len == 0 the
   * name is absent entirely and ie->name aliases whatever bytes
   * follow this record - that is the actual out-of-bounds read
   * to guard against. (Corrected after review feedback that the
   * original 'ie->len < 6' guard overshot the real bug class.) */
  if (ie->len == 0) {
    return;
  }
  if (strncmp(ie->name, "event", strlen("event") + 1) == 0) {
    if (ie->mask & IN_CREATE) {
      attach_input_device(ie->name);
    } else {
      detach_input_device(ie->name);
    }
  }
}

static void handle_inotify_events(void) {
  static char *read_buf = NULL;
  ssize_t read_len = 0;

  if (read_buf == NULL) {
    read_buf = safe_calloc(INOTIFY_READ_BUF_LEN, sizeof(char));
  }

  while (true) {
    read_len = read(inotify_fd, read_buf, INOTIFY_READ_BUF_LEN);
    if (read_len == -1) {
      if (errno == EINTR) {
        continue;
      }
      fprintf(stderr,
        "FATAL ERROR: Could not read from inotify file descriptor: %s\n",
        strerror(errno));
      exit(1);
    }
    break;
  }

  parse_inotify_buffer(read_buf, read_len, dispatch_inotify_event);
}


/* calc_poll_timeout()'s saturating int64 subtraction moved to
 * src/kloak_poll_timeout.inc.h as kloak_poll_timeout_pure();
 * this wrapper pulls the queue head and current time. */
static int calc_poll_timeout(void) {
  const struct input_packet *packet = NULL;

  packet = TAILQ_FIRST(&evq_head);
  if (packet == NULL) {
    return -1;
  }
  return kloak_poll_timeout_pure(packet->sched_time, current_time_ms());
}

